#!/bin/sh
# Builds the MT7925 I/Q pump and writes it as ../mt7925_pump.h.  Not part of the normal
# build: the header is kept in the tree, so only changes to iqpump.c need clang with the
# riscv32 target and llvm-objcopy.
#
#   CLANG=clang-15 OBJCOPY=llvm-objcopy-15 ./mkpump.sh

set -e
cd "$(dirname "$0")"

CLANG=${CLANG:-clang}
OBJCOPY=${OBJCOPY:-llvm-objcopy}
OBJDUMP=${OBJDUMP:-llvm-objdump}
# Where the host puts the control block; mt7925_host.c checks it against the header
CTL_ADDR=0x0090c000
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT

$CLANG -target riscv32 -march=rv32imc -mabi=ilp32 -mno-relax -Os -ffreestanding -fno-builtin \
    -fno-jump-tables -fno-pic -fno-asynchronous-unwind-tables -fno-stack-protector \
    -Wall -Werror -Wno-int-to-pointer-cast -DCTL_ADDR=${CTL_ADDR}u -c iqpump.c -o "$tmp/iqpump.o"

# The pump is copied to an arbitrary address and entered at its first byte
if $OBJDUMP -r "$tmp/iqpump.o" | grep -q R_RISCV; then
    echo "iqpump.o has relocations" >&2
    exit 1
fi
if [ "$($OBJDUMP -h "$tmp/iqpump.o" | awk '$2 ~ /^\.(data|bss|rodata|sdata|sbss)/ && $3 != "00000000"')" != "" ]; then
    echo "iqpump.o has data sections" >&2
    exit 1
fi
$OBJCOPY -O binary -j .text.entry "$tmp/iqpump.o" "$tmp/iqpump.bin"
# The host loads it in words
truncate -s %4 "$tmp/iqpump.bin"

{
    echo "/* Generated by mt7925_pump/mkpump.sh from mt7925_pump/iqpump.c; do not edit */"
    echo "#ifndef MT7925_PUMP_H"
    echo "#define MT7925_PUMP_H"
    echo
    echo "#include <stdint.h>"
    echo
    echo "#define MT7925_PUMP_CTL_ADDR ${CTL_ADDR}u"
    echo
    echo "static const uint8_t mt7925_pump_code[] = {"
    od -An -v -tx1 "$tmp/iqpump.bin" | sed 's/  */ /g; s/^ //; s/ $//; s/\([0-9a-f][0-9a-f]\)/0x\1,/g; s/^/    /'
    echo "};"
    echo
    echo "#endif"
} > ../mt7925_pump.h
echo "wrote ../mt7925_pump.h ($(wc -c < "$tmp/iqpump.bin") bytes)"
