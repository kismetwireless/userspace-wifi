#define ROR(x, n) ((x) >> (n) | (x) << (32 - (n)))

static void sha256_block(uint32_t h[8], const uint8_t *p) {
    uint32_t w[64], a, b, c, d, e, f, g, hh, t1, t2;
    int i;

    for (i = 0; i < 16; i++)
        w[i] = (uint32_t) p[4 * i] << 24 | (uint32_t) p[4 * i + 1] << 16 | (uint32_t) p[4 * i + 2] << 8 | p[4 * i + 3];
    for (i = 16; i < 64; i++)
        w[i] = w[i - 16] + (ROR(w[i - 15], 7) ^ ROR(w[i - 15], 18) ^ w[i - 15] >> 3) + w[i - 7] +
               (ROR(w[i - 2], 17) ^ ROR(w[i - 2], 19) ^ w[i - 2] >> 10);
    a = h[0], b = h[1], c = h[2], d = h[3], e = h[4], f = h[5], g = h[6], hh = h[7];
    for (i = 0; i < 64; i++) {
        t1 = hh + (ROR(e, 6) ^ ROR(e, 11) ^ ROR(e, 25)) + ((e & f) ^ (~e & g)) + k256[i] + w[i];
        t2 = (ROR(a, 2) ^ ROR(a, 13) ^ ROR(a, 22)) + ((a & b) ^ (a & c) ^ (b & c));
        hh = g, g = f, f = e, e = d + t1, d = c, c = b, b = a, a = t1 + t2;
    }
    h[0] += a, h[1] += b, h[2] += c, h[3] += d, h[4] += e, h[5] += f, h[6] += g, h[7] += hh;
}

/* the digest of data as lowercase hex */
static void sha256_hex(const uint8_t *data, size_t len, char out[65]) {
    uint32_t h[8] = { 0x6a09e667, 0xbb67ae85, 0x3c6ef372, 0xa54ff53a, 0x510e527f, 0x9b05688c, 0x1f83d9ab, 0x5be0cd19 };
    uint8_t tail[128] = { 0 };
    size_t full = len / 64 * 64, rest = len - full, tlen = rest < 56 ? 64 : 128, i;
    uint64_t bits = (uint64_t) len * 8;

    for (i = 0; i < full; i += 64)
        sha256_block(h, data + i);
    memcpy(tail, data + full, rest);
    tail[rest] = 0x80;
    for (i = 0; i < 8; i++)
        tail[tlen - 1 - i] = (uint8_t) (bits >> (8 * i));
    for (i = 0; i < tlen; i += 64)
        sha256_block(h, tail + i);
    for (i = 0; i < 32; i++) {
        static const char digits[] = "0123456789abcdef";
        uint8_t v = (uint8_t) (h[i / 4] >> (24 - 8 * (i % 4)));

        out[2 * i] = digits[v >> 4];
        out[2 * i + 1] = digits[v & 15];
    }
    out[64] = '\0';
}

static int hexval(char c) {
    return c <= '9' ? c - '0' : c - 'a' + 10;
}

int mt7961_fw_state(const uint8_t *data, size_t len) {
    char sha[65];

    if (len != FW_SIZE)
        return MT7961_FW_OTHER;
    sha256_hex(data, len, sha);
    if (strcmp(sha, patched_sha256) == 0)
        return MT7961_FW_PATCHED;
    return strcmp(sha, stock_sha256) == 0 ? MT7961_FW_STOCK : MT7961_FW_OTHER;
}

int mt7961_fw_patch(uint8_t *data, size_t len) {
    size_t i, k, n;

    if (mt7961_fw_state(data, len) != MT7961_FW_STOCK)
        return -1;
    for (i = 0; i < sizeof(runs) / sizeof(runs[0]); i++) {
        n = strlen(runs[i].hex) / 2;
        for (k = 0; k < n; k++)
            data[runs[i].off + k] = (uint8_t) (hexval(runs[i].hex[2 * k]) << 4 | hexval(runs[i].hex[2 * k + 1]));
    }
    return mt7961_fw_state(data, len) == MT7961_FW_PATCHED ? 0 : -1;
}

/* other firmware, and firmware this patch isn't for, goes through as it is */
int mt7961_fw_filter(const char *name, uint8_t **data, size_t *len) {
    if (strcmp(name, FW_NAME) == 0 && mt7961_fw_state(*data, *len) == MT7961_FW_STOCK &&
        mt7961_fw_patch(*data, *len) < 0)
        return -EINVAL;
    return 0;
}
